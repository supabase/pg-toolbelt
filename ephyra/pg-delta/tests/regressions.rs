//! Shrunk counterexamples from the Ephyra runs, as plain tests. Each fails on
//! pg-delta main (1d34a62a) with empty tables, in both compact modes.

use pg_delta_ephyra::migrate_bare;

fn converges(from: &str, to: &str) {
    let fails: Vec<String> = [true, false]
        .into_iter()
        .map(|compact| (compact, migrate_bare(from, to, compact)))
        .filter(|(_, o)| o.verdict != "pass")
        .map(|(compact, o)| format!("compact={compact} {}: {}", o.kind, o.detail))
        .collect();
    assert!(fails.is_empty(), "{}", fails.join("\n"));
}

#[test]
fn identity_added_to_nullable_column() {
    converges("CREATE TABLE t1 (c2 integer);", "CREATE TABLE t1 (c2 integer GENERATED ALWAYS AS IDENTITY);");
}

#[test]
fn default_of_new_enum_type_set_before_type_exists() {
    converges(
        "CREATE TABLE t1 (c1 text);",
        "CREATE TYPE e1 AS ENUM ('green'); CREATE TABLE t1 (c1 e1 DEFAULT 'green');",
    );
}

#[test]
fn default_set_before_column_retype_to_domain() {
    converges("CREATE TABLE t2 (c1 integer);", "CREATE DOMAIN d0 AS text; CREATE TABLE t2 (c1 d0 DEFAULT 'x');");
}

#[test]
fn identity_added_before_retype_to_integer() {
    converges("CREATE TABLE t3 (c0 boolean);", "CREATE TABLE t3 (c0 integer GENERATED BY DEFAULT AS IDENTITY);");
}

#[test]
fn retype_keeps_column_collation() {
    converges("CREATE TABLE t1 (c0 text COLLATE \"C\");", "CREATE TABLE t1 (c0 character varying(10) COLLATE \"C\");");
}

#[test]
fn retype_between_types_without_a_cast() {
    converges("CREATE TABLE t3 (c0 text[]);", "CREATE TABLE t3 (c0 integer);");
}

#[test]
fn fk_survives_retype_of_both_ends() {
    converges(
        "CREATE TABLE t2 (id text PRIMARY KEY); CREATE TABLE t3 (t2_id text REFERENCES t2 (id));",
        "CREATE TABLE t2 (id uuid PRIMARY KEY); CREATE TABLE t3 (t2_id uuid REFERENCES t2 (id));",
    );
}

#[test]
fn add_column_of_constrained_domain_declares_rewrite() {
    converges(
        "CREATE TABLE t2 (c1 smallint);",
        "CREATE DOMAIN d0 AS integer CHECK (VALUE > 0); CREATE TABLE t2 (c1 smallint, c0 d0);",
    );
}

#[test]
fn enum_rebuild_with_dependent_policy() {
    converges(
        "CREATE TYPE e0 AS ENUM ('green', 'red'); CREATE TABLE t1 (c4 e0); CREATE POLICY p1 ON t1 USING (c4 IS NOT NULL);",
        "CREATE TYPE e0 AS ENUM ('red'); CREATE TABLE t1 (c4 e0); CREATE POLICY p1 ON t1 USING (c4 IS NOT NULL);",
    );
}
