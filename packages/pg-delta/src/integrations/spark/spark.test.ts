import { describe, expect, test } from "bun:test";
import type { SparkSchemaDescription } from "./description.ts";
import { sparkFactBase } from "./fact-base.ts";
import {
  exportSparkSchema,
  planSparkFactBases,
  planSparkSchema,
  sparkStatusDiagnostics,
} from "./frontend.ts";
import { todosDescription } from "./todos.fixture.ts";

const emptyProject = (): SparkSchemaDescription => {
  const d = todosDescription();
  return {
    ...d,
    enums: [],
    views: [],
    tables: d.tables.filter((t) => t.managed),
  };
};

const planBetween = (a: SparkSchemaDescription, b: SparkSchemaDescription) =>
  planSparkFactBases(sparkFactBase(a), sparkFactBase(b), b.managed_schemas);

describe("spark source", () => {
  test("identical descriptions plan no changes", () => {
    const { plan, sql } = planBetween(todosDescription(), todosDescription());
    expect(plan.actions).toHaveLength(0);
    expect(sql).toBe("");
  });

  test("empty project to todos creates every user object and leaves auth alone", () => {
    const { sql } = planBetween(emptyProject(), todosDescription());
    expect(sql).toMatchInlineSnapshot(`
      "CREATE TABLE "public"."todos" ("id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL, "user_id" uuid NOT NULL, "title" text NOT NULL, "done" boolean DEFAULT false, CONSTRAINT "todos_pkey" PRIMARY KEY (id), CONSTRAINT "todos_title_check" CHECK ((length(title) > 0)));

      ALTER TABLE "public"."todos" ENABLE ROW LEVEL SECURITY;

      CREATE TYPE "public"."status" AS ENUM ('todo', 'done');

      ALTER TABLE "public"."todos" ADD COLUMN "status" public.status NOT NULL DEFAULT 'todo'::public.status;

      ALTER TABLE "public"."todos" ADD COLUMN "created_at" timestamp with time zone DEFAULT now();

      ALTER TABLE "public"."todos" ADD CONSTRAINT "todos_user_id_fkey" FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE;

      CREATE VIEW "public"."open_todos" AS  SELECT id,
          title
         FROM public.todos
        WHERE (NOT done);

      CREATE INDEX todos_user_id_idx ON public.todos USING btree (user_id);

      CREATE POLICY "own todos" ON "public"."todos" FOR ALL TO PUBLIC USING ((user_id = user_id));

      COMMENT ON TABLE "public"."todos" IS 'things to do';
      "
    `);
  });

  test("an added column and a dropped index plan minimal DDL", () => {
    const desired = todosDescription();
    const todos = desired.tables[1]!;
    todos.columns.push({
      name: "notes",
      position: 7,
      type: "text",
      not_null: false,
      default: null,
      identity: null,
      generated: null,
      comment: null,
    });
    todos.indexes = todos.indexes.filter((i) => i.name !== "todos_user_id_idx");
    const { sql } = planBetween(todosDescription(), desired);
    expect(sql).toMatchInlineSnapshot(`
      "DROP INDEX "public"."todos_user_id_idx";

      ALTER TABLE "public"."todos" ADD COLUMN "notes" text;
      "
    `);
  });

  test("managed tables and schemas are reference only", () => {
    const fb = sparkFactBase(todosDescription());
    expect(
      fb.isReferenceOnly({ kind: "table", schema: "auth", name: "users" }),
    ).toBe(true);
    expect(fb.isReferenceOnly({ kind: "schema", name: "auth" })).toBe(true);
    expect(
      fb.isReferenceOnly({ kind: "table", schema: "public", name: "todos" }),
    ).toBe(false);
    expect(
      fb.facts().some((f) => f.id.kind === "role" || f.id.kind === "acl"),
    ).toBe(false);
  });

  test("grouped export renders the user schema only", () => {
    const files = exportSparkSchema(todosDescription());
    expect(files.map((f) => f.name)).toMatchInlineSnapshot(`
      [
        "public/types/status.sql",
        "public/tables/todos.sql",
        "public/views/open_todos.sql",
      ]
    `);
    expect(files.map((f) => f.sql).join("\n")).not.toContain("auth.users (");
  });

  test("statuses map to diagnostics", () => {
    const diags = sparkStatusDiagnostics([
      { file: "a.sql", index: 0, line: 1, kind: "CreateStmt", status: "ok" },
      {
        file: "a.sql",
        index: 1,
        line: 4,
        kind: "GrantStmt",
        status: "ignored",
      },
      {
        file: "a.sql",
        index: 2,
        line: 9,
        kind: "CreateFunctionStmt",
        status: "unsupported",
        message: "functions",
      },
    ]);
    expect(diags.map((d) => [d.code, d.severity, d.message])).toEqual([
      ["spark-ignored", "info", "a.sql:4 GrantStmt ignored"],
      [
        "spark-unsupported",
        "error",
        "a.sql:9 CreateFunctionStmt unsupported: functions",
      ],
    ]);
  });

  test("planSparkSchema proves the plan against a scratch replay", async () => {
    const requests: { path: string; body: unknown }[] = [];
    const fakeFetch = (async (input: string, init?: { body?: string }) => {
      const path = new URL(input).pathname;
      const body = init?.body ? JSON.parse(init.body) : undefined;
      requests.push({ path, body });
      const payload =
        path === "/_spark/v1/schema"
          ? emptyProject()
          : { statuses: [], schema: todosDescription() };
      return new Response(JSON.stringify(payload), { status: 200 });
    }) as unknown as typeof fetch;
    const result = await planSparkSchema(
      { url: "http://spark.test/", key: "k", fetch: fakeFetch },
      [{ name: "todos.sql", sql: "create table ..." }],
    );
    expect(result.sql).toContain(`CREATE TABLE "public"."todos"`);
    expect(result.proof?.ok).toBe(true);
    expect(
      requests.map((r) => [
        r.path,
        (r.body as { base?: string } | undefined)?.base,
      ]),
    ).toEqual([
      ["/_spark/v1/schema", undefined],
      ["/_spark/v1/scratch", "empty"],
      ["/_spark/v1/scratch", "current"],
    ]);
  });
});
