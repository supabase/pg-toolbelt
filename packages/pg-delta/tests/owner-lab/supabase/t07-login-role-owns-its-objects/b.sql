create role app_login login password 'secret-pass';
grant create on schema public to app_login;
grant app_login to postgres;
set role app_login;
create table public.mine (id bigint generated by default as identity primary key, body text);
alter table public.mine enable row level security;
create policy mine_read on public.mine for select to authenticated using (true);
grant select on public.mine to authenticated;
create function public.mine_count() returns bigint language sql stable as $$ select count(*) from public.mine $$;
reset role;
revoke app_login from postgres;
