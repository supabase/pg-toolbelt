CREATE ROLE app_owner NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE SCHEMA app;
GRANT USAGE ON SCHEMA app TO authenticated;
GRANT USAGE, CREATE ON SCHEMA app TO app_owner;
GRANT app_owner TO current_user;
SET ROLE app_owner;
CREATE TABLE app.todos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT gen_random_uuid(),
  title text NOT NULL DEFAULT '',
  done boolean NOT NULL DEFAULT false,
  inserted_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE app.todos ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON app.todos TO authenticated;
ALTER TABLE app.todos ADD COLUMN is_public boolean NOT NULL DEFAULT false;
CREATE POLICY "Users can read own or public todos" ON app.todos FOR SELECT TO authenticated
  USING (is_public OR user_id = nullif(current_setting('request.jwt.claim.sub', true), '')::uuid);
CREATE POLICY "Users can insert own todos" ON app.todos FOR INSERT TO authenticated
  WITH CHECK (user_id = nullif(current_setting('request.jwt.claim.sub', true), '')::uuid);
CREATE POLICY "Users can update own todos" ON app.todos FOR UPDATE TO authenticated
  USING (user_id = nullif(current_setting('request.jwt.claim.sub', true), '')::uuid)
  WITH CHECK (user_id = nullif(current_setting('request.jwt.claim.sub', true), '')::uuid);
ALTER TABLE app.todos FORCE ROW LEVEL SECURITY;
RESET ROLE;
REVOKE CREATE ON SCHEMA app FROM app_owner;
REVOKE app_owner FROM current_user;
