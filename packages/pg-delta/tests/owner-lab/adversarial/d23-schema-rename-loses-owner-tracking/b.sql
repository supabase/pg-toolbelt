CREATE ROLE h_hold NOLOGIN;
CREATE ROLE o_own NOLOGIN;
CREATE ROLE x_reader NOLOGIN;
CREATE SCHEMA s2;
CREATE SCHEMA q;
GRANT USAGE, CREATE ON SCHEMA s2 TO o_own;
GRANT USAGE, CREATE ON SCHEMA q TO h_hold, o_own;
CREATE TABLE q.u (id int, n1 int);
CREATE TABLE q.w (id int, n2 int);
CREATE TABLE s2.t (id int, v text, z int);
GRANT h_hold TO current_user;
GRANT o_own TO current_user;
ALTER TABLE q.u OWNER TO h_hold;
ALTER TABLE q.w OWNER TO o_own;
ALTER TABLE s2.t OWNER TO o_own;
SET ROLE o_own;
GRANT SELECT ON s2.t TO h_hold WITH GRANT OPTION;
GRANT SELECT ON s2.t TO x_reader;
RESET ROLE;
REVOKE h_hold FROM current_user;
REVOKE o_own FROM current_user;
