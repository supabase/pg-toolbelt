CREATE ROLE r1 NOLOGIN;
CREATE ROLE r2 NOLOGIN;
CREATE SCHEMA s;
GRANT USAGE, CREATE ON SCHEMA s TO r1, r2;
GRANT r1, r2 TO current_user;
CREATE TABLE s.par (id int);
CREATE TABLE s.chi () INHERITS (s.par);
CREATE TABLE s.ppar (id int) PARTITION BY RANGE (id);
CREATE TABLE s.pp1 PARTITION OF s.ppar FOR VALUES FROM (0) TO (100);
ALTER TABLE s.par OWNER TO r1;
ALTER TABLE s.chi OWNER TO r2;
ALTER TABLE s.ppar OWNER TO r1;
ALTER TABLE s.pp1 OWNER TO r2;
REVOKE r1, r2 FROM current_user;
