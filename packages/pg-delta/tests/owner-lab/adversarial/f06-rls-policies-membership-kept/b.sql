CREATE ROLE app_owner NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
GRANT CREATE ON SCHEMA public TO app_owner;
-- granted by hand once, kept
GRANT app_owner TO current_user;
SET ROLE app_owner;
CREATE TABLE public.todos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT gen_random_uuid(),
  title text NOT NULL DEFAULT '',
  done boolean NOT NULL DEFAULT false,
  inserted_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.todos ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.todos TO authenticated;
ALTER TABLE public.todos ADD COLUMN is_public boolean NOT NULL DEFAULT false;
CREATE POLICY "Users can read own or public todos" ON public.todos FOR SELECT TO authenticated
  USING (is_public OR user_id = nullif(current_setting('request.jwt.claim.sub', true), '')::uuid);
CREATE POLICY "Users can insert own todos" ON public.todos FOR INSERT TO authenticated
  WITH CHECK (user_id = nullif(current_setting('request.jwt.claim.sub', true), '')::uuid);
CREATE POLICY "Users can update own todos" ON public.todos FOR UPDATE TO authenticated
  USING (user_id = nullif(current_setting('request.jwt.claim.sub', true), '')::uuid)
  WITH CHECK (user_id = nullif(current_setting('request.jwt.claim.sub', true), '')::uuid);
RESET ROLE;
