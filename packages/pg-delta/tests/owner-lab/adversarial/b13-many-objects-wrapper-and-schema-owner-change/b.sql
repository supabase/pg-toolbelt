CREATE ROLE o1 NOLOGIN;
CREATE ROLE o2 NOLOGIN;
CREATE ROLE r NOLOGIN;
DO $$ BEGIN EXECUTE format('GRANT CREATE ON DATABASE %I TO o1, o2', current_database()); END $$;
CREATE SCHEMA s;
GRANT USAGE ON SCHEMA s TO r;
CREATE TABLE s.t1 (id int GENERATED ALWAYS AS IDENTITY, v int);
CREATE TABLE s.t2 (id serial);
CREATE FUNCTION s.f() RETURNS int LANGUAGE sql AS 'select 1';
CREATE TYPE s.ty AS ENUM ('a');
GRANT CREATE ON SCHEMA s TO r;
GRANT r, o2 TO current_user;
ALTER TABLE s.t1 OWNER TO r;
ALTER TABLE s.t2 OWNER TO r;
ALTER FUNCTION s.f() OWNER TO r;
ALTER TYPE s.ty OWNER TO r;
REVOKE CREATE ON SCHEMA s FROM r;
ALTER SCHEMA s OWNER TO o2;
REVOKE r, o2 FROM current_user;
