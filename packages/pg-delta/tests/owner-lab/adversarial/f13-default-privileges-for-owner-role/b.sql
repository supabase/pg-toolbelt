CREATE ROLE app_owner NOLOGIN;
CREATE ROLE reader NOLOGIN;
CREATE ROLE writer NOLOGIN;
CREATE SCHEMA app;
GRANT USAGE ON SCHEMA app TO reader, writer;
GRANT USAGE, CREATE ON SCHEMA app TO app_owner;
GRANT app_owner TO current_user;
SET ROLE app_owner;
CREATE TABLE app.customers (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, name text);
ALTER DEFAULT PRIVILEGES IN SCHEMA app GRANT SELECT ON TABLES TO reader;
ALTER DEFAULT PRIVILEGES IN SCHEMA app GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO writer;
ALTER DEFAULT PRIVILEGES IN SCHEMA app GRANT USAGE, SELECT ON SEQUENCES TO writer;
ALTER DEFAULT PRIVILEGES REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
GRANT SELECT ON app.customers TO reader;
GRANT SELECT, INSERT, UPDATE, DELETE ON app.customers TO writer;
CREATE TABLE app.orders (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  customer_id bigint REFERENCES app.customers (id),
  total_cents bigint NOT NULL DEFAULT 0
);
RESET ROLE;
REVOKE app_owner FROM current_user;
