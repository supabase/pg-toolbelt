CREATE ROLE o_own NOLOGIN;
CREATE ROLE x_reader NOLOGIN;
CREATE SCHEMA s;
GRANT USAGE, CREATE ON SCHEMA s TO o_own;
GRANT o_own TO current_user;
ALTER DEFAULT PRIVILEGES FOR ROLE o_own IN SCHEMA s GRANT SELECT ON TABLES TO x_reader;
ALTER DEFAULT PRIVILEGES FOR ROLE o_own GRANT EXECUTE ON FUNCTIONS TO x_reader WITH GRANT OPTION;
REVOKE o_own FROM current_user;
