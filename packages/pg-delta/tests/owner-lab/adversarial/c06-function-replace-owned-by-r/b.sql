CREATE ROLE r NOLOGIN;
CREATE ROLE x NOLOGIN;
CREATE SCHEMA s;
GRANT USAGE, CREATE ON SCHEMA s TO r;
ALTER DEFAULT PRIVILEGES REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
CREATE FUNCTION s.f() RETURNS bigint LANGUAGE sql AS 'select 1::bigint';
GRANT r TO current_user;
ALTER FUNCTION s.f() OWNER TO r;
GRANT EXECUTE ON FUNCTION s.f() TO x;
REVOKE r FROM current_user;
