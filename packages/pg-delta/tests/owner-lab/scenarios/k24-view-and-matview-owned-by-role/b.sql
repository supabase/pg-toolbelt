CREATE SCHEMA s;
CREATE ROLE r NOLOGIN;
GRANT USAGE, CREATE ON SCHEMA s TO r;
CREATE TABLE s.t (id int);
CREATE VIEW s.v AS SELECT id FROM s.t;
CREATE MATERIALIZED VIEW s.mv AS SELECT id FROM s.t;
CREATE TYPE s.pair AS (a int, b int);
CREATE DOMAIN s.posint AS int CHECK (VALUE > 0);
CREATE SEQUENCE s.seq;
GRANT SELECT ON s.t TO r;
GRANT r TO current_user;
ALTER VIEW s.v OWNER TO r;
ALTER MATERIALIZED VIEW s.mv OWNER TO r;
ALTER TYPE s.pair OWNER TO r;
ALTER DOMAIN s.posint OWNER TO r;
ALTER SEQUENCE s.seq OWNER TO r;
REVOKE r FROM current_user;
