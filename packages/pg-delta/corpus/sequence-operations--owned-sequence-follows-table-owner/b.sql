-- state B: the same tables owned by owner_b. ALTER TABLE … OWNER TO carries
-- each linked sequence; Postgres refuses ALTER SEQUENCE … OWNER TO on a
-- sequence linked to a table, so the plan must not re-own it on its own.
CREATE ROLE owner_a;
CREATE ROLE owner_b;
CREATE SCHEMA app;
CREATE TABLE app.serial_t (id serial PRIMARY KEY, note text);
CREATE TABLE app.identity_t (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, note text);
CREATE TABLE app.owned_t (id integer PRIMARY KEY, note text);
CREATE SEQUENCE app.owned_t_id_seq OWNED BY app.owned_t.id;
ALTER TABLE app.serial_t OWNER TO owner_b;
ALTER TABLE app.identity_t OWNER TO owner_b;
ALTER TABLE app.owned_t OWNER TO owner_b;
