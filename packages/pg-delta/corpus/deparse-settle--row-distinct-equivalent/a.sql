-- The flat spelling Postgres settles on: semantically identical to b.sql.
CREATE SCHEMA s;

CREATE FUNCTION s.tf() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN RETURN NEW; END$$;

CREATE DOMAIN s.dm AS int
  CHECK ((VALUE IS DISTINCT FROM 1) OR (VALUE IS DISTINCT FROM 2) OR (VALUE IS DISTINCT FROM 3));
CREATE DOMAIN s.dm_default AS boolean
  DEFAULT ((length(current_user::text) IS DISTINCT FROM 1) OR (2 IS DISTINCT FROM 2) OR (3 IS DISTINCT FROM 3));

CREATE TABLE s.t (
  a int,
  b int,
  c int,
  g boolean GENERATED ALWAYS AS ((a IS DISTINCT FROM 1) OR (b IS DISTINCT FROM 2) OR (c IS DISTINCT FROM 3)) STORED,
  d boolean DEFAULT ((length(current_user::text) IS DISTINCT FROM 1) OR (2 IS DISTINCT FROM 2) OR (3 IS DISTINCT FROM 3)),
  CONSTRAINT ck CHECK ((a IS DISTINCT FROM 1) OR (b IS DISTINCT FROM 2) OR (c IS DISTINCT FROM 3)),
  CONSTRAINT ck_not CHECK (NOT ((a IS DISTINCT FROM a) OR (b IS DISTINCT FROM b) OR (c IS DISTINCT FROM c)))
);

CREATE INDEX ix_pred ON s.t (a)
  WHERE (a IS DISTINCT FROM 1) OR (b IS DISTINCT FROM 2) OR (c IS DISTINCT FROM 3);
CREATE INDEX ix_expr ON s.t
  ((((a IS DISTINCT FROM 1) OR (b IS DISTINCT FROM 2) OR (c IS DISTINCT FROM 3))));

CREATE VIEW s.v AS SELECT a FROM s.t
  WHERE (a IS DISTINCT FROM 1) OR (b IS DISTINCT FROM 2) OR (c IS DISTINCT FROM 3);
CREATE MATERIALIZED VIEW s.mv AS SELECT a FROM s.t
  WHERE (a IS DISTINCT FROM 1) OR (b IS DISTINCT FROM 2) OR (c IS DISTINCT FROM 3);

ALTER TABLE s.t ENABLE ROW LEVEL SECURITY;
CREATE POLICY p ON s.t
  USING ((a IS DISTINCT FROM 1) OR (b IS DISTINCT FROM 2) OR (c IS DISTINCT FROM 3))
  WITH CHECK ((a IS DISTINCT FROM 1) OR (b IS DISTINCT FROM 2) OR (c IS DISTINCT FROM 3));

CREATE TABLE s.r (a int, b int, c int);
CREATE TABLE s.rlog (n int);
CREATE RULE ru AS ON UPDATE TO s.r
  WHERE (old.a IS DISTINCT FROM new.a) OR (old.b IS DISTINCT FROM new.b) OR (old.c IS DISTINCT FROM new.c)
  DO ALSO INSERT INTO s.rlog VALUES (1);
CREATE TRIGGER tg AFTER UPDATE ON s.r FOR EACH ROW
  WHEN ((OLD.a IS DISTINCT FROM NEW.a) OR (OLD.b IS DISTINCT FROM NEW.b) OR (OLD.c IS DISTINCT FROM NEW.c))
  EXECUTE FUNCTION s.tf();

CREATE FUNCTION s.fs(a int, b int, c int) RETURNS boolean
  LANGUAGE sql IMMUTABLE
  RETURN (a IS DISTINCT FROM 1) OR (b IS DISTINCT FROM 2) OR (c IS DISTINCT FROM 3);
